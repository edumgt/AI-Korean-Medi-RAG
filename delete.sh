#!/bin/bash

# ==========================================
# 설정 변수 (본인의 환경에 맞게 수정하세요)
# ==========================================
TARGET_DIR="/home/ubuntu/aihub-rag"  # 삭제를 시작할 대상 폴더 경로
EXTENSION="Identifier"      # 삭제할 파일의 확장자

# ==========================================
# 실행 로직
# ==========================================

# 대상 폴더 존재 여부 확인
if [ ! -d "$TARGET_DIR" ]; then
    echo "오류: '$TARGET_DIR' 폴더가 존재하지 않습니다."
    exit 1
fi

echo "=================================================="
echo "대상 폴더: $TARGET_DIR"
echo "대상 확장자: *.$EXTENSION"
echo "=================================================="

# 1단계: 삭제 대상 파일 목록 미리보기 (안전 확인)
echo "현재 검색된 삭제 대상 파일 목록입니다:"
find "$TARGET_DIR" -type f -name "*.$EXTENSION"

echo "--------------------------------------------------"
read -p "위의 파일들을 정말로 '삭제'하시겠습니까? (y/N): " CONFIRM

if [[ "$CONFIRM" =~ ^[Yy]$ ]]; then
    echo "파일 삭제를 시작합니다..."
    # 실제 삭제 수행
    find "$TARGET_DIR" -type f -name "*.$EXTENSION" -delete
    echo "선택하신 확장자의 모든 파일이 삭제되었습니다."
else
    echo "삭제 작업이 취소되었습니다."
fi